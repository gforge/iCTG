#!/usr/bin/env python3
"""Record a training run in the benchmark history and regenerate docs/BENCHMARKS.md.

    uv run python scripts/record_benchmark.py --metrics artifacts_ctg3/metrics_random_init.json \\
        --name random_init --cohort 76855 --notes "first run on the rebuilt cohort"

Each run becomes one JSON file under benchmarks/ (metrics only, no patient data) so the
history is versioned with the code; the markdown table is rebuilt from all of them.
"""

from __future__ import annotations

import argparse
import json
import subprocess
from datetime import date
from pathlib import Path

ML_DIR = Path(__file__).resolve().parent.parent
BENCH_DIR = ML_DIR / "benchmarks"
DOC_PATH = ML_DIR / "docs" / "BENCHMARKS.md"


def _git_commit() -> str:
    try:
        return subprocess.check_output(
            ["git", "rev-parse", "--short", "HEAD"], cwd=ML_DIR, text=True
        ).strip()
    except Exception:  # noqa: BLE001
        return "unknown"


def entry_from_metrics(
    metrics_path: Path, name: str, cohort: int | None, seeds: int, notes: str
) -> dict:
    payload = json.loads(metrics_path.read_text())
    test = payload["test_metrics"]
    outcomes: dict[str, dict[str, float]] = {}
    for group in ("derived_binary", "binary"):
        for outcome, values in test.get(group, {}).items():
            if isinstance(values, dict) and "roc_auc" in values:
                outcomes[outcome] = {
                    "roc_auc": float(values["roc_auc"]),
                    "pr_auc": float(values["pr_auc"]),
                    "prevalence": float(values.get("prevalence", float("nan"))),
                }
    return {
        "name": name,
        "date": date.today().isoformat(),
        "commit": _git_commit(),
        "cohort": cohort,
        "split": "mother-level 70/15/15",
        "seeds": seeds,
        "seed": payload.get("seed"),
        "init_encoder": payload.get("init_encoder") or "",
        "freeze_encoder_epochs": payload.get("freeze_encoder_epochs"),
        "modality_mode": payload.get("modality_mode"),
        "notes": notes,
        "summary": {
            "apgar5_mae": test.get("apgar5_mae"),
            "mean_binary_pr_auc": test.get("mean_binary_pr_auc"),
            "monitor_binary_pr_auc": test.get("monitor_binary_pr_auc"),
        },
        "outcomes": outcomes,
    }


def load_entries() -> list[dict]:
    entries = [json.loads(p.read_text()) for p in sorted(BENCH_DIR.glob("*.json"))]
    return sorted(entries, key=lambda e: (e.get("date", ""), e.get("name", "")))


def render_markdown(entries: list[dict]) -> str:
    lines = [
        "# Benchmarks",
        "",
        "Test-set results per run, regenerated by `scripts/record_benchmark.py` from the JSON",
        "files in `benchmarks/`. Metrics are ROC-AUC / PR-AUC on the held-out test split.",
        "PR-AUC is the informative number for these rare outcomes; the random-ranking baseline",
        "for PR-AUC equals the prevalence. Single-seed runs are noisier than multi-seed means.",
        "",
        "## Runs",
        "",
        "| Run | Date | Commit | Cohort | Split | Seeds | Encoder init | Mean binary PR-AUC | Apgar5 MAE | Notes |",
        "|---|---|---|---:|---|---:|---|---:|---:|---|",
    ]
    for e in entries:
        s = e.get("summary", {})
        mean_pr = s.get("mean_binary_pr_auc")
        mae = s.get("apgar5_mae")
        lines.append(
            f"| {e['name']} | {e.get('date', '')} | {e.get('commit', '')} | {e.get('cohort') or ''} | "
            f"{e.get('split', '')} | {e.get('seeds', '')} | {e.get('init_encoder') or 'random'} | "
            f"{mean_pr:.3f} | {mae:.3f} | {e.get('notes', '')} |"
            if isinstance(mean_pr, float) and isinstance(mae, float)
            else f"| {e['name']} | {e.get('date', '')} | {e.get('commit', '')} | {e.get('cohort') or ''} | "
            f"{e.get('split', '')} | {e.get('seeds', '')} | {e.get('init_encoder') or 'random'} | | | {e.get('notes', '')} |"
        )
    outcomes: list[str] = []
    for e in entries:
        for name in e.get("outcomes", {}):
            if name not in outcomes:
                outcomes.append(name)
    lines += ["", "## Per outcome (ROC-AUC / PR-AUC, test)", ""]
    header = "| Outcome | Prevalence | " + " | ".join(e["name"] for e in entries) + " |"
    lines.append(header)
    lines.append("|---|---:|" + "---:|" * len(entries))
    for outcome in outcomes:
        prev = ""
        for e in reversed(entries):
            v = e.get("outcomes", {}).get(outcome)
            if v and v.get("prevalence") == v.get("prevalence"):  # not NaN
                prev = f"{100 * v['prevalence']:.2f} %"
                break
        cells = []
        for e in entries:
            v = e.get("outcomes", {}).get(outcome)
            cells.append(f"{v['roc_auc']:.3f} / {v['pr_auc']:.3f}" if v else "")
        lines.append(f"| {outcome} | {prev} | " + " | ".join(cells) + " |")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--metrics", help="metrics JSON written by train_multimodal_tcn.py --metrics-out"
    )
    parser.add_argument("--name", help="short run name (becomes part of the file name)")
    parser.add_argument(
        "--cohort", type=int, default=None, help="number of pregnancies in the cohort"
    )
    parser.add_argument("--seeds", type=int, default=1)
    parser.add_argument("--notes", default="")
    parser.add_argument("--render-only", action="store_true", help="only regenerate the markdown")
    args = parser.parse_args()

    BENCH_DIR.mkdir(exist_ok=True)
    if not args.render_only:
        if not args.metrics or not args.name:
            parser.error("--metrics and --name are required unless --render-only")
        entry = entry_from_metrics(
            Path(args.metrics), args.name, args.cohort, args.seeds, args.notes
        )
        out = BENCH_DIR / f"{entry['date']}_{args.name}.json"
        out.write_text(json.dumps(entry, indent=2) + "\n")
        print(f"Recorded {out}")
    DOC_PATH.parent.mkdir(exist_ok=True)
    DOC_PATH.write_text(render_markdown(load_entries()))
    print(f"Wrote {DOC_PATH}")


if __name__ == "__main__":
    main()
